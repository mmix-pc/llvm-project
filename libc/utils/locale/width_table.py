"""Import the selected UTF-8 charmap's display widths, not encoding mappings."""

import argparse
import hashlib
import json
from pathlib import Path
import re


def parse(text):
    starts = list(re.finditer(r'^WIDTH\s*$', text, re.M))
    ends = list(re.finditer(r'^END WIDTH\s*$', text, re.M))
    if len(starts) != 1 or len(ends) != 1 or starts[0].end() >= ends[0].start():
        raise ValueError('expected one WIDTH section')
    ranges = []
    for line in text[starts[0].end():ends[0].start()].splitlines():
        line = line.split('%', 1)[0].strip()
        if not line:
            continue
        match = re.fullmatch(r'<U([0-9A-Fa-f]{4,8})>(?:\.\.\.<U([0-9A-Fa-f]{4,8})>)?\s+([012])', line)
        if not match:
            raise ValueError('unsupported width record')
        first, last = int(match[1], 16), int(match[2] or match[1], 16)
        if first > last or last > 0x10ffff or first <= 0xdfff and last >= 0xd800:
            raise ValueError('invalid width scalar range')
        ranges.append((first, last, int(match[3])))
    if not ranges or len(ranges) > 65536:
        raise ValueError('invalid width record count')
    ranges.sort()
    for previous, current in zip(ranges, ranges[1:]):
        if previous[1] >= current[0]:
            raise ValueError('overlapping width ranges')
    return ranges


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    with args.source.open('rb') as stream:
        raw = stream.read(8 * 1024 * 1024 + 1)
    if len(raw) > 8 * 1024 * 1024:
        parser.error('width source exceeds bound')
    text = raw.decode('utf-8')
    ranges = parse(text)
    include = ('// Generated by libc/utils/locale/width_table.py.\n'
               '// Source identity and original notices: width_table.json.\n')
    include += ''.join('    {0x%x, 0x%x, %d},\n' % row for row in ranges)
    manifest = dict(sha256=hashlib.sha256(raw).hexdigest(), source=args.source.name,
                    header=re.split(r'^CHARMAP\s*$', text, maxsplit=1, flags=re.M)[0],
                    width_preamble=text.split('END CHARMAP', 1)[1].split('\nWIDTH', 1)[0],
                    ranges=len(ranges), default_printable_width=1)
    for suffix, content in (('.inc', include), ('.json', json.dumps(
            manifest, ensure_ascii=True, indent=2, sort_keys=True) + '\n')):
        path = args.output.with_suffix(suffix)
        if args.check:
            if path.read_text(encoding='utf-8') != content:
                parser.error('generated widths differ: ' + str(path))
        else:
            path.write_text(content, encoding='utf-8')


if __name__ == '__main__':
    main()
