"""Embed the reviewed neutral/combining rules without a target file dependency."""

import argparse
import hashlib
import json
from pathlib import Path

from ctype_source import SourceReader
from locale_file import encode_locale
from transliteration_category import transliteration_records

SOURCES = ("translit_neutral", "translit_combining")


def generate(root):
    reader = SourceReader(root)
    rules = {}
    for name in SOURCES:
        category = reader.read(name)
        if category['classes'] or category['maps']:
            raise ValueError('builtin transliteration must not replace character tables')
        rules.update(category['transliterations'])
    data = encode_locale(dict(
        name='builtin-transliteration',
        categories=[transliteration_records(dict(transliterations=rules)),
                    [], [], [], [], []]))
    lines = ['// Generated by libc/utils/locale/builtin_transliteration.py.',
             '// Source identities and original notices: builtin_transliteration.json.',
             '// clang-format off']
    for start in range(0, len(data), 32):
        lines.append('"' + ''.join('\\x%02x' % byte for byte in data[start:start + 32]) + '"')
    lines.append('// clang-format on')
    manifest = dict(source_order=list(SOURCES), sources=reader.files,
                    edges=reader.edges, rules=len(rules), bytes=len(data),
                    sha256=hashlib.sha256(data).hexdigest())
    return '\n'.join(lines) + '\n', manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-root', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    include, manifest = generate(args.source_root)
    outputs = {args.output.with_suffix('.inc'): include,
               args.output.with_suffix('.json'):
               json.dumps(manifest, ensure_ascii=True, indent=2, sort_keys=True) + '\n'}
    for path, contents in outputs.items():
        if args.check:
            if path.read_text(encoding='utf-8') != contents:
                parser.error('generated data differs: ' + str(path))
        else:
            path.write_text(contents, encoding='utf-8')


if __name__ == '__main__':
    main()
